def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    OUT_SWIFT.parent.mkdir(parents=True, exist_ok=True)
    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    OUT_SWIFT.write_text(gen_swift(data), encoding="utf-8")
    OUT_KT.write_text(gen_kotlin(data), encoding="utf-8")
    android_assets = (
        ROOT / "android" / "corridor-panel" / "app" / "src" / "main" / "assets"
    )
    android_assets.mkdir(parents=True, exist_ok=True)
    (android_assets / "corridor_topics.json").write_text(
        SRC.read_text(encoding="utf-8"), encoding="utf-8"
    )
    mac_res = ROOT / "macos" / "CorridorPanel" / "CorridorPanel" / "Resources"
    mac_res.mkdir(parents=True, exist_ok=True)
    (mac_res / "corridor_topics.json").write_text(
        SRC.read_text(encoding="utf-8"), encoding="utf-8"
    )
    print(f"wrote {OUT_SWIFT.relative_to(ROOT)}")
    print(f"wrote {OUT_KT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
